/**
 * 빌드 전에 rules/JIRA.md 내용을 src/protocol.ts로 내장합니다.
 * 이렇게 하면 빌드된 결과물이 외부 파일 경로에 의존하지 않습니다.
 */
import { readFileSync, writeFileSync } from "fs";
import { resolve, dirname } from "path";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const protocolPath = resolve(__dirname, "../../../rules/JIRA.md");
const outputPath = resolve(__dirname, "../src/protocol.ts");

const content = readFileSync(protocolPath, "utf-8");
const escaped = JSON.stringify(content);

writeFileSync(
  outputPath,
  `// Auto-generated by scripts/embed-protocol.js — DO NOT EDIT\nexport const JIRA_PROTOCOL = ${escaped};\n`
);

console.log("✓ JIRA protocol embedded into src/protocol.ts");
